export const SIMPLE_COPY = { en, hi };

// "{name} is on" -> fills {name}
export const fill = (text, values = {}) => String(text || "").replace(/\{(\w+)\}/g, (whole, key) => (values[key] !== undefined ? String(values[key]) : whole));

const LANG_KEY = "eazotel.actions.lang";
const readLang = () => {
  try {
    return localStorage.getItem(LANG_KEY) === "hi" ? "hi" : "en";
  } catch {
    return "en";
  }
};

export const useSimpleCopy = () => {
  const [lang, setLangState] = useState(readLang);
  const setLang = useCallback((next) => {
    setLangState(next);
    try {
      localStorage.setItem(LANG_KEY, next);
    } catch {
      // private window: the choice lasts for this visit only
    }
  }, []);
  return { copy: SIMPLE_COPY[lang], lang, setLang };
};
